import type { ParseResult, RawSong } from './parse.ts';

/** One record per line: stable, diff-friendly, byte-identical for the same input. */
export function serializeSongs(songs: RawSong[]): string {
  const rows = songs.map((s) =>
    JSON.stringify({ n: s.n, t: s.t, a: s.a, page: s.page, col: s.col }),
  );
  return rows.length ? `[\n${rows.join(',\n')}\n]\n` : '[]\n';
}

export interface ReportInput {
  result: ParseResult;
  /** Source file name (no directory) and its SHA-256, to tie a report to one exact PDF. */
  sourceName: string;
  sourceSha256: string;
  pageCount: number;
}

export function findDuplicates(songs: RawSong[]): RawSong[][] {
  const groups: RawSong[][] = [];
  let i = 0;
  while (i < songs.length) {
    let j = i + 1;
    while (j < songs.length && songs[j]!.n === songs[i]!.n) j++;
    if (j - i > 1) groups.push(songs.slice(i, j));
    i = j;
  }
  return groups;
}

const cell = (s: string): string => s.replace(/\|/g, '\\|');
const rec = (s: RawSong): string =>
  `n=${s.n}, page ${s.page} col ${s.col}: title "${s.t}", artist "${s.a}"`;

export function renderReport(input: ReportInput): string {
  const { result, sourceName, sourceSha256, pageCount } = input;
  const { songs, rejects, pages, anchors, reassembly } = result;
  const rejectedAnchors = rejects.reduce((s, r) => s + r.anchors, 0);
  const dups = findDuplicates(songs);
  const dupRows = dups.reduce((s, g) => s + g.length, 0);
  const outOfRange = rejects.filter((r) => r.reason === 'number outside 1..99999');
  const emptyTitle = songs.filter((s) => s.t === '');
  const emptyArtist = songs.filter((s) => s.a === '');
  const ign = pages.reduce(
    (acc, p) => ({
      header: acc.header + p.ignored.header,
      footer: acc.footer + p.ignored.footer,
      other: acc.other + p.ignored.other,
    }),
    { header: 0, footer: 0, other: 0 },
  );
  const balanced = songs.length + rejectedAnchors === anchors;

  const L: string[] = [];
  L.push('# Import report');
  L.push('');
  L.push('Generated by `npm run import`. Do not edit by hand; re-run the import instead.');
  L.push('');
  L.push(`- Source: \`${sourceName}\` (SHA-256 \`${sourceSha256}\`), ${pageCount} pages`);
  L.push('');
  L.push('## Summary');
  L.push('');
  L.push(`- Rows parsed: **${songs.length}**`);
  L.push(`- Number anchors detected (integers in the NO. column): ${anchors}`);
  L.push(`- Rows rejected: **${rejects.length}** (accounting for ${rejectedAnchors} anchors)`);
  L.push(
    `- Check: parsed + rejected anchors = ${songs.length + rejectedAnchors}, detected anchors = ${anchors}: **${balanced ? 'balanced, nothing dropped silently' : 'MISMATCH'}**`,
  );
  L.push(`- Distinct song numbers: ${new Set(songs.map((s) => s.n)).size}`);
  L.push(`- Duplicate song numbers: **${dups.length}** numbers across ${dupRows} rows (listed below, none overwritten)`);
  L.push(`- Numbers outside 1..99999: **${outOfRange.length}**`);
  L.push(`- Rows with empty title: **${emptyTitle.length}**; with empty artist: **${emptyArtist.length}**`);
  L.push('');
  L.push('## Wrapped rows');
  L.push('');
  L.push(
    `**${reassembly.rows} rows were reassembled from more than one visual line** (of ${songs.length} parsed).`,
  );
  L.push('');
  L.push(`- with a wrapped title: ${reassembly.titleWrapped}`);
  L.push(`- with a wrapped artist: ${reassembly.artistWrapped}`);
  L.push(`- number not on the first line (vertically centred in the row): ${reassembly.numberOffFirstLine}`);
  L.push(`- numbers with no text in their band (kept with empty title and artist): ${reassembly.numberWithoutText}`);
  L.push('');
  L.push(
    'A row is anchored by its number. Title and artist words are grouped into visual lines, consecutive lines less than 10.5 pt apart form one row band (wrapped lines are about 9 pt apart, separate rows at least 11.5 pt), and the number is attached to the band whose first-to-last line span contains it (the number is vertically centred in wrapped rows). A band with exactly one number is joined, with single spaces, in reading order. Anything else is rejected below.',
  );
  L.push('');
  L.push('## Rejected rows');
  L.push('');
  if (!rejects.length) L.push('None.');
  else {
    L.push('| Page | Column | Reason | Raw text |');
    L.push('|------|--------|--------|----------|');
    for (const r of rejects) L.push(`| ${r.page} | ${r.col ?? '-'} | ${r.reason} | ${cell(r.raw)} |`);
  }
  L.push('');
  L.push('## Duplicate song numbers');
  L.push('');
  if (!dups.length) L.push('None.');
  else
    for (const g of dups) {
      L.push(`- **${g[0]!.n}** (${g.length} rows)`);
      for (const s of g) L.push(`  - ${rec(s)}`);
    }
  L.push('');
  L.push('## Numbers outside 1..99999');
  L.push('');
  if (!outOfRange.length) L.push('None.');
  else for (const r of outOfRange) L.push(`- page ${r.page} col ${r.col ?? '-'}: ${r.raw}`);
  L.push('');
  L.push('## Rows with empty title or empty artist');
  L.push('');
  const empties = songs.filter((s) => s.t === '' || s.a === '');
  if (!empties.length) L.push('None.');
  else
    for (const s of empties)
      L.push(`- ${rec(s)} (${s.t === '' ? 'empty title' : ''}${s.t === '' && s.a === '' ? ', ' : ''}${s.a === '' ? 'empty artist' : ''})`);
  L.push('');
  L.push('## Ignored words');
  L.push('');
  L.push(
    `Page header words (NO. / TITLE / ARTIST): ${ign.header}; footer words (running footer and page number): ${ign.footer}; other words outside the table body: ${ign.other}.`,
  );
  L.push('');
  L.push('## Rows parsed per page');
  L.push('');
  L.push('| Page | Left col | Right col | Total | Reassembled | Rejected |');
  L.push('|------|---------:|----------:|------:|------------:|---------:|');
  for (const p of pages)
    L.push(`| ${p.page} | ${p.left} | ${p.right} | ${p.left + p.right} | ${p.reassembled} | ${p.rejects} |`);
  L.push(`| **Total** | ${pages.reduce((s, p) => s + p.left, 0)} | ${pages.reduce((s, p) => s + p.right, 0)} | ${songs.length} | ${reassembly.rows} | ${rejects.length} |`);
  L.push('');
  return L.join('\n');
}
